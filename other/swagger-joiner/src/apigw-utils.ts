import type {
  DocumentationVersion,
  ExportResponse,
} from "@aws-sdk/client-api-gateway";
import {
  APIGatewayClient,
  CreateDocumentationVersionCommand,
  GetDocumentationVersionsCommand,
  GetExportCommand,
} from "@aws-sdk/client-api-gateway";
import { logger } from "@digitraffic/common/dist/aws/runtime/dt-logger-default";
import type { OpenApiSchema } from "@digitraffic/common/dist/types/openapi-schema";
import { isObject } from "es-toolkit/compat";

export async function exportSwaggerApi(apiId: string): Promise<ExportResponse> {
  const exportCommand = new GetExportCommand({
    restApiId: apiId,
    exportType: "oas30",
    stageName: "prod",
  });

  const apigateway = new APIGatewayClient();
  return apigateway.send(exportCommand);
}

interface DocumentationVersionResult {
  readonly apiId: string;
  readonly versions?: DocumentationVersion[];
}

export async function getDocumentationVersion(
  apiId: string,
  apigateway: APIGatewayClient,
): Promise<DocumentationVersionResult> {
  const getDocumentationVersionsCommand = new GetDocumentationVersionsCommand({
    limit: 500,
    restApiId: apiId,
  });

  const result = await apigateway.send(getDocumentationVersionsCommand);

  return {
    apiId,
    versions: result.items,
  };
}

/**
 * Creates a new API Gateway documentation version snapshot.
 * The version identifier is an arbitrary string provided by the caller —
 * this function does not interpret or modify it.
 */
export function createDocumentationVersion(
  apiId: string,
  documentationVersion: string,
  apigateway: APIGatewayClient,
): Promise<DocumentationVersion> {
  logger.info({
    method: "APIGWUtils.createDocumentationVersion",
    customApiId: apiId,
    customDocumentationVersion: documentationVersion,
  });

  const updateApiCommand = new CreateDocumentationVersionCommand({
    restApiId: apiId,
    stageName: "prod",
    documentationVersion,
  });

  return apigateway.send(updateApiCommand);
}

/**
 * Makes exactly one alternative accept null, in this order of preference:
 * 1. the first typed alternative without enum (gets `nullable: true`),
 * 2. the first typed enum alternative (gets `nullable: true` and null in its enum),
 * 3. the first enum alternative without type (gets null in its enum; nullable needs a type),
 * 4. otherwise a new `{ enum: [null] }` alternative is added.
 *
 * Examples:
 * ```
 * 1. [{ type: "string", enum: ["A"] }, { type: "string" }]
 *    -> [{ type: "string", enum: ["A"] }, { type: "string", nullable: true }]
 * 2. [{ type: "string", enum: ["A"] }, { type: "number", enum: [1] }]
 *    -> [{ type: "string", enum: ["A", null], nullable: true }, { type: "number", enum: [1] }]
 * 3. [{ enum: ["A"] }, { enum: ["B"] }]
 *    -> [{ enum: ["A", null] }, { enum: ["B"] }]
 * 4. [{ minLength: 1 }, { pattern: "a" }]
 *    -> [{ minLength: 1 }, { pattern: "a" }, { enum: [null] }]
 * ```
 */
function markOneAlternativeNullable(alternatives: unknown[]): unknown[] {
  const schemas = alternatives as Record<string, unknown>[];
  const isTyped = (schema: Record<string, unknown>): boolean =>
    // biome-ignore lint/complexity/useLiteralKeys: index signature requires bracket notation
    isObject(schema) && schema["type"] !== undefined;
  const hasEnum = (schema: Record<string, unknown>): boolean =>
    // biome-ignore lint/complexity/useLiteralKeys: index signature requires bracket notation
    isObject(schema) && Array.isArray(schema["enum"]);
  const firstIndex = (
    predicate: (schema: Record<string, unknown>) => boolean,
  ): number => schemas.findIndex(predicate);

  const target = [
    firstIndex((schema) => isTyped(schema) && !hasEnum(schema)),
    firstIndex((schema) => isTyped(schema) && hasEnum(schema)),
    firstIndex((schema) => hasEnum(schema)),
  ].find((index) => index >= 0);

  if (target === undefined) {
    return [...schemas, { enum: [null] }];
  }

  return schemas.map((schema, index) => {
    if (index !== target) {
      return schema;
    }
    // biome-ignore lint/complexity/useLiteralKeys: index signature requires bracket notation
    const enumValues = schema["enum"];
    return {
      ...schema,
      ...(isTyped(schema) ? { nullable: true } : {}),
      ...(Array.isArray(enumValues) && !enumValues.includes(null)
        ? { enum: [...enumValues, null] }
        : {}),
    };
  });
}

/**
 * Recursively walks a schema object and transforms broken `anyOf: [schema, null]`
 * or similar oneOf structures generated by API Gateway back into a valid OpenAPI 3.0 format
 * with `nullable: true`. Lists with more than one non-null alternative (e.g. open enums)
 * keep their alternatives, and one of them is made to accept null. This function mutates the object.
 *
 * Examples (API Gateway turns `{ type: "null" }` into `null`):
 *
 * One non-null alternative is merged into the parent:
 * ```
 * { description: "Name", anyOf: [{ type: "string" }, null] }
 * -> { description: "Name", type: "string", nullable: true }
 * ```
 *
 * Several non-null alternatives (e.g. an open enum) are kept. Exactly one typed alternative
 * (preferably one without enum) gets `nullable: true`, because OpenAPI 3.0 applies nullable
 * only next to a type and oneOf allows only one match. The list itself is not marked nullable:
 * ```
 * { anyOf: [{ type: "string", enum: ["A", "B"] }, { type: "string", minLength: 1 }, null] }
 * -> { anyOf: [{ type: "string", enum: ["A", "B"] }, { type: "string", minLength: 1, nullable: true }] }
 * ```
 *
 * Lists without `null` are left untouched:
 * ```
 * { anyOf: [{ type: "string" }, { type: "number" }] }
 * -> { anyOf: [{ type: "string" }, { type: "number" }] }
 * ```
 *
 * @param schema The schema object to fix.
 */
export function fixApiGatewayNullable(schema: OpenApiSchema): void {
  if (!isObject(schema)) {
    return;
  }

  const toVisit: Record<string, unknown>[] = [schema];
  const visited = new Set<unknown>();

  while (toVisit.length > 0) {
    const current = toVisit.pop();

    if (!isObject(current) || visited.has(current)) {
      continue;
    }

    visited.add(current);

    // Determine if the current object has a broken `anyOf` or `oneOf` structure
    const compositionKey = ["anyOf", "oneOf"].find(
      (key) =>
        Array.isArray(current[key]) &&
        (current[key] as unknown[]).length >= 2 &&
        (current[key] as unknown[]).includes(null),
    );

    if (compositionKey) {
      const nonNullParts = (current[compositionKey] as unknown[]).filter(
        (x) => x !== null,
      );

      if (nonNullParts.length > 1) {
        // Several alternatives (e.g. open enum): keep them and let exactly one accept null.
        // In OpenAPI 3.0 nullable only has effect next to an explicit type and an enum must
        // list null explicitly. Only one alternative may match null, so that oneOf stays valid.
        current[compositionKey] = markOneAlternativeNullable(nonNullParts);
      } else if (isObject(nonNullParts[0])) {
        const schemaPart = nonNullParts[0] as Record<string, unknown>;
        logger.debug({
          message: `Fixing nullable field with ${compositionKey}: ${JSON.stringify(
            current,
          )}`,
        });

        // Delete the broken anyOf
        delete current[compositionKey];

        // Merge the properties from the actual schema part
        for (const key in schemaPart) {
          if (Object.hasOwn(schemaPart, key)) {
            current[key] = schemaPart[key];
          }
        }
        // Add the correct nullable property
        // biome-ignore lint/complexity/useLiteralKeys: nope
        current["nullable"] = true;
        // nullable does not extend an enum, so null must be listed explicitly
        // biome-ignore lint/complexity/useLiteralKeys: nope
        const mergedEnum = current["enum"];
        if (Array.isArray(mergedEnum) && !mergedEnum.includes(null)) {
          // biome-ignore lint/complexity/useLiteralKeys: nope
          current["enum"] = [...mergedEnum, null];
        }

        logger.debug({
          message: `Fixed nullable field ${JSON.stringify(current)}`,
        });
      }
    }

    // Find nested objects/arrays to visit next
    for (const key in current) {
      if (Object.hasOwn(current, key)) {
        const value = current[key] as Record<string, unknown>;
        if (isObject(value) || Array.isArray(value)) {
          toVisit.push(value);
        }
      }
    }
  }
}
